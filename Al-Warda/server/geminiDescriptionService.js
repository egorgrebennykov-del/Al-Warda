/**
 * Gemini-powered perfume description generation.
 *
 * Step 4 of the Al-Warda product pipeline:
 *   Qogita data -> photo generation -> aroma palette -> DESCRIPTION (Gemini).
 *
 * The description is written strictly from the confirmed aroma palette (the
 * top/heart/base notes) in Russian and English and stored in `stocks.info` as
 * `descriptionRu` / `descriptionEn` with `descriptionSource = "gemini"`.
 *
 * The API key is read from `GEMINI_API_KEY` (worker binding or process env) and
 * must never be shipped to the browser.
 */

// Free-tier Gemini applies a per-model per-day quota (500 requests) in addition
// to a per-minute one, so we keep several flash-class models available and fall
// through to the next one when a model is throttled or exhausted.
const GEMINI_MODELS = [
  "gemini-3.1-flash-lite",
  "gemini-3.1-flash-lite-preview",
  "gemini-3.5-flash-lite",
  "gemini-3-flash-preview",
  "gemini-3.5-flash",
  // Thinking-class models answer more slowly but return clean JSON and are
  // served under their own per-day quota, so they keep the pipeline alive once
  // the fast flash models are exhausted.
  "gemini-3.7-flash",
  // Last-resort fallbacks: Gemma models served by the same Generative Language
  // API. They have their own daily quota, no systemInstruction/responseMimeType
  // support, and emit a separate "thought" part before the answer, so both the
  // request body and the response parsing are adapted for them.
  "gemma-4-26b-a4b-it",
  "gemma-4-31b-it",
];
const GEMINI_TIMEOUT_MS = 20000;
const GEMINI_RETRIES = 3;
const GEMINI_RETRY_DELAY_MS = 1000;
const MIN_DESCRIPTION_LENGTH = 160;

function delay(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

// Same markers the storefront uses to recognise boilerplate descriptions
// (utils/perfumes.js#isGenericOrShortDescription). A row whose description is
// still boilerplate must be regenerated by Gemini from the aroma palette.
const GENERIC_DESCRIPTION_MARKERS = [
  "Сертифицированная оригинальная",
  "оригинальный премиальный парфюм",
  "премиальный оригинальный арабский",
  "Роскошный восточный аромат Al-Warda",
  "Поставляется напрямую со складов",
  "Delivered directly from certified distribution hubs",
  "exquisite authentic luxury Arabian fragrance",
];

function isGenericOrShortDescription(text) {
  const clean = String(text || "").trim();
  if (clean.length < MIN_DESCRIPTION_LENGTH) return true;
  return GENERIC_DESCRIPTION_MARKERS.some((marker) => clean.includes(marker));
}

export function getGeminiApiKey(env) {
  return (
    env?.GEMINI_API_KEY ||
    env?.VITE_GEMINI_API_KEY ||
    globalThis.process?.env?.GEMINI_API_KEY ||
    globalThis.process?.env?.VITE_GEMINI_API_KEY ||
    ""
  );
}

const DESCRIPTION_SYSTEM_INSTRUCTION = `You are a senior copywriter for Al-Warda, a luxury Arabian perfume boutique.
You write elegant, evocative product descriptions that are faithful to the fragrance's real aroma palette.
You never invent notes, brands, accords or countries of origin that were not provided.
You return strict JSON only, without markdown or extra text.`;

function isGemmaModel(model) {
  return /^gemma/i.test(model);
}

function modelTimeoutMs(model) {
  // Gemma narrates its reasoning and thinking-class models deliberate first, so
  // both need a longer window than the flash models.
  if (isGemmaModel(model)) return 90000;
  if (/^gemini-3\.[78]/.test(model)) return 120000;
  return GEMINI_TIMEOUT_MS;
}

function buildRequestBody(model, prompt) {
  // Gemma models reject systemInstruction/responseMimeType, so fold the system
  // instruction into the prompt and rely on the JSON extractor instead.
  if (isGemmaModel(model)) {
    const text = `${DESCRIPTION_SYSTEM_INSTRUCTION}\n\n${prompt}\n\nOutput ONLY the JSON object and nothing else. Do not narrate, explain or restate the rules.`;
    return {
      contents: [{ role: "user", parts: [{ text }] }],
      generationConfig: { temperature: 0.7, maxOutputTokens: 8192 },
    };
  }
  return {
    systemInstruction: { parts: [{ text: DESCRIPTION_SYSTEM_INSTRUCTION }] },
    contents: [{ role: "user", parts: [{ text: prompt }] }],
    generationConfig: {
      responseMimeType: "application/json",
      temperature: 0.7,
      maxOutputTokens: 1200,
    },
  };
}

function notesToText(notes) {
  const bucket = notes?.en && typeof notes.en === "object" ? notes.en : notes || {};
  const layer = (key) => (Array.isArray(bucket[key]) ? bucket[key].filter(Boolean).join(", ") : "");
  return {
    top: layer("top"),
    heart: layer("heart"),
    base: layer("base"),
  };
}

function buildPrompt({ name, brand, notes, category }) {
  const palette = notesToText(notes);
  const lines = [
    `Fragrance name: ${name || "unknown"}`,
    `Brand / house: ${brand || "unknown"}`,
  ];
  if (category) lines.push(`Fragrance family: ${category}`);
  lines.push("Aroma palette (use these exact notes, never add others):");
  lines.push(`- Top notes: ${palette.top || "not specified"}`);
  lines.push(`- Heart notes: ${palette.heart || "not specified"}`);
  lines.push(`- Base notes: ${palette.base || "not specified"}`);
  lines.push("");
  lines.push("Write the product description for this exact fragrance.");
  lines.push("Rules:");
  lines.push("- The description MUST be built from the aroma palette above.");
  lines.push("- descriptionRu: 2 to 4 polished sentences in natural Russian.");
  lines.push("- descriptionEn: the same description in natural English.");
  lines.push("- Evocative and premium in tone; no exclamation marks, no marketing clichés.");
  lines.push("- Never invent notes, accords, brands, ingredients or origins.");
  lines.push('Respond with JSON only: {"descriptionRu":"...","descriptionEn":"..."}');

  return lines.join("\n");
}

// Walk every balanced {...} block and keep the last one that carries a
// description. Verbose models (e.g. Gemma) narrate their reasoning and only
// emit the final JSON object at the very end, sometimes without a code fence.
function lastDescriptionObject(text) {
  let result = null;
  for (let i = 0; i < text.length; i += 1) {
    if (text[i] !== "{") continue;
    let depth = 0;
    for (let j = i; j < text.length; j += 1) {
      if (text[j] === "{") depth += 1;
      else if (text[j] === "}") {
        depth -= 1;
        if (depth === 0) {
          try {
            const obj = JSON.parse(text.slice(i, j + 1));
            if (obj && (obj.descriptionRu || obj.descriptionEn)) result = obj;
          } catch {
            // not valid JSON: keep scanning
          }
          break;
        }
      }
    }
  }
  return result;
}

function extractJsonObject(content) {
  const text = String(content || "").trim();
  if (!text) return null;
  const fenced = text.match(/```(?:json)?\s*([\s\S]*?)```/i);
  const candidates = [];
  if (fenced) candidates.push(fenced[1].trim());
  candidates.push(text);
  for (const candidate of candidates) {
    try {
      return JSON.parse(candidate);
    } catch {
      const start = candidate.indexOf("{");
      const end = candidate.lastIndexOf("}");
      if (start !== -1 && end > start) {
        try {
          return JSON.parse(candidate.slice(start, end + 1));
        } catch {
          // keep looking
        }
      }
    }
  }
  return lastDescriptionObject(text);
}

function clean(value) {
  return String(value || "").replace(/\s+/g, " ").trim().slice(0, 1200);
}

// Thinking models (Gemma, Gemini thinking variants) return their reasoning in
// one or more `thought` parts and the actual answer in the remaining part(s).
// Reading only `parts[0]` therefore yields the model's rambling notes instead of
// the JSON, so prefer the non-thought parts and fall back to all of them.
function candidateText(data) {
  const parts = data?.candidates?.[0]?.content?.parts;
  if (!Array.isArray(parts) || parts.length === 0) return "";
  const answer = parts.filter((part) => part && part.thought !== true && typeof part?.text === "string");
  const chosen = answer.length > 0 ? answer : parts;
  return chosen.map((part) => (typeof part?.text === "string" ? part.text : "")).join("");
}

/**
 * Generate RU/EN perfume descriptions from the aroma palette.
 * Returns `null` when Gemini is not configured or cannot answer, so the caller
 * can fall back to the template-based description.
 */
export async function generatePerfumeDescriptions({ name, brand, notes, category, env } = {}) {
  const apiKey = getGeminiApiKey(env);
  if (!apiKey) return null;

  const prompt = buildPrompt({ name, brand, notes, category });

  // Each attempt walks every model in order: a throttled/exhausted model is
  // skipped immediately instead of burning the whole backoff window, so the
  // per-minute and per-day quotas are spread across the available models.
  for (let attempt = 1; attempt <= GEMINI_RETRIES; attempt += 1) {
    let sawRetryable = false;
    for (const model of GEMINI_MODELS) {
      const controller = typeof AbortController !== "undefined" ? new AbortController() : null;
      const timer = controller && typeof setTimeout === "function" ? setTimeout(() => controller.abort(), modelTimeoutMs(model)) : null;
      try {
        const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
        const response = await fetch(url, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify(buildRequestBody(model, prompt)),
          signal: controller?.signal,
        });
        if (!response.ok) {
          if (response.status === 429 || response.status >= 500) sawRetryable = true;
          continue; // try the next model
        }

        const data = await response.json();
        const parsed = extractJsonObject(candidateText(data));
        const descriptionRu = clean(parsed?.descriptionRu);
        const descriptionEn = clean(parsed?.descriptionEn);
        if (!descriptionRu && !descriptionEn) continue;

        return {
          descriptionRu: descriptionRu || descriptionEn,
          descriptionEn: descriptionEn || descriptionRu,
          source: "gemini",
          model,
          generatedAt: new Date().toISOString(),
        };
      } catch {
        sawRetryable = true;
      } finally {
        if (timer) clearTimeout(timer);
      }
    }
    if (!sawRetryable) break; // no model gave a retryable failure: stop early
    if (attempt < GEMINI_RETRIES) await delay(GEMINI_RETRY_DELAY_MS * attempt);
  }
  return null;
}

/**
 * Merge Gemini descriptions into a stock row's `info` object.
 * Regenerates when the description is missing or still boilerplate; never
 * overwrites a real description unless `overwrite` is true.
 */
export async function withGeminiDescriptions(info, { name, brand, notes, category, env, overwrite = false } = {}) {
  const next = { ...(info && typeof info === "object" ? info : {}) };
  const hasRealDescription = !isGenericOrShortDescription(next.descriptionRu);
  if (hasRealDescription && !overwrite) return next;

  const descriptions = await generatePerfumeDescriptions({ name, brand, notes, category, env });
  if (!descriptions) return next;

  next.descriptionRu = descriptions.descriptionRu;
  next.descriptionEn = descriptions.descriptionEn;
  next.descriptionSource = "gemini";
  next.descriptionsLookup = {
    source: "gemini",
    model: descriptions.model,
    checkedAt: descriptions.generatedAt,
  };
  return next;
}

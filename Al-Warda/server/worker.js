function syncProcessEnv(env) {
  if (!globalThis.process) {
    globalThis.process = { env: {} };
  }
  if (!globalThis.process.env) {
    globalThis.process.env = {};
  }
  Object.assign(globalThis.process.env, workerEnv || {}, env || {});
}

function enrichPerfumeObj(p) {
  if (!p) return p;
  // Notes are only trusted when they were generated by DeepSeek or entered
  // manually. The old heuristic fallback invented notes from the name,
  // so it must never be used here.
  const info = p.info && typeof p.info === "object" ? p.info : {};
  const verifiedNotes =
    info.notesVerified === true && info.notes && typeof info.notes === "object"
      ? info.notes
      : null;

  const pick = (...values) => {
    for (const value of values) {
      if (Array.isArray(value) && value.length > 0) return value;
    }
    return [];
  };

  const topRu = pick(verifiedNotes?.ru?.top, verifiedNotes?.en?.top);
  const heartRu = pick(verifiedNotes?.ru?.heart, verifiedNotes?.en?.heart);
  const baseRu = pick(verifiedNotes?.ru?.base, verifiedNotes?.en?.base);
  const topEn = pick(verifiedNotes?.en?.top, topRu);
  const heartEn = pick(verifiedNotes?.en?.heart, heartRu);
  const baseEn = pick(verifiedNotes?.en?.base, baseRu);

  return {
    ...p,
    origin: p.origin || "Ближний Восток",
    originEn: p.originEn || "Middle East",
    topNotes: topRu,
    heartNotes: heartRu,
    baseNotes: baseRu,
    topNotesRu: topRu,
    heartNotesRu: heartRu,
    baseNotesRu: baseRu,
    topNotesEn: topEn,
    heartNotesEn: heartEn,
    baseNotesEn: baseEn,
    notesVerified: Boolean(verifiedNotes),
    notesSource: info.notesSource || p.notesSource || null,
    notesLookup: info.notesLookup || p.notesLookup || null,
  };
}

function completedProductPhoto(perfume) {
  const generation = perfume?.info?.imageGeneration;
  const image = generation?.imageUrl || perfume?.image;
  const isManual = Boolean(perfume?.info?.manual || generation?.manual);
  if (
    generation?.status !== "completed" ||
    (!isGeneratedProductImage(image) && !isManual)
  ) {
    return null;
  }
  return { ...perfume, image, fullCardImage: image };
}

export function isReadyProduct(perfume) {
  return Boolean(completedProductPhoto(perfume));
}

function jsonResponse(body, status = 200) {
  return new Response(JSON.stringify(body), {
    status,
    headers: {
      "Content-Type": "application/json; charset=utf-8",
      "Access-Control-Allow-Origin": "*",
      "Access-Control-Allow-Methods": "GET, POST, OPTIONS, PATCH, DELETE",
      "Access-Control-Allow-Headers": "Content-Type, Authorization, apikey",
    },
  });
}

async function serveGeneratedProductImage(request, pathname, env, ctx) {
  const match =
    /^\/assets\/img\/generated-products\/([a-f0-9]{64})\.(png|webp)$/.exec(
      pathname,
    );
  if (!match) return null;

  const hash = match[1];
  const requestedExt = match[2];
  const etag = `W/"${hash}"`;

  // 1. Fast 304 check on client-provided If-None-Match
  const ifNoneMatch = request.headers.get("if-none-match");
  if (
    ifNoneMatch &&
    (ifNoneMatch === etag ||
      ifNoneMatch === hash ||
      ifNoneMatch.includes(hash))
  ) {
    return new Response(null, {
      status: 304,
      headers: {
        "Cache-Control":
          "public, max-age=31536000, s-maxage=31536000, immutable",
        ETag: etag,
        "Access-Control-Allow-Origin": "*",
        Vary: "Accept",
      },
    });
  }

  // 2. Check Cloudflare Edge Cache API (caches.default)
  const cache =
    typeof caches !== "undefined" && caches.default ? caches.default : null;
  const acceptHeader = request.headers.get("accept") || "";
  const supportsWebp = acceptHeader.includes("image/webp");

  const cacheUrl = new URL(request.url);
  if (supportsWebp && requestedExt === "png") {
    cacheUrl.searchParams.set("format", "webp");
  }
  const cacheKey = new Request(cacheUrl.toString(), { method: "GET" });

  if (cache) {
    try {
      const cached = await cache.match(cacheKey);
      if (cached) {
        return cached;
      }
    } catch {
      // cache match failed, proceed to fetch
    }
  }

  // 3. Try serving from env.ASSETS first if available
  if (env?.ASSETS) {
    try {
      if (supportsWebp) {
        const webpReq = new Request(
          new URL(`/assets/img/generated-products/${hash}.webp`, request.url),
        );
        const webpRes = await env.ASSETS.fetch(webpReq);
        if (webpRes && webpRes.ok) {
          const headers = new Headers(webpRes.headers);
          headers.set("Content-Type", "image/webp");
          headers.set(
            "Cache-Control",
            "public, max-age=31536000, s-maxage=31536000, immutable",
          );
          headers.set("ETag", etag);
          headers.set("Access-Control-Allow-Origin", "*");
          headers.set("Vary", "Accept");
          const finalRes = new Response(webpRes.body, { status: 200, headers });
          if (cache && ctx?.waitUntil) {
            ctx.waitUntil(cache.put(cacheKey, finalRes.clone()));
          }
          return finalRes;
        }
      }

      const assetRes = await env.ASSETS.fetch(request);
      if (assetRes && assetRes.ok) {
        const headers = new Headers(assetRes.headers);
        headers.set(
          "Content-Type",
          requestedExt === "webp" ? "image/webp" : "image/png",
        );
        headers.set(
          "Cache-Control",
          "public, max-age=31536000, s-maxage=31536000, immutable",
        );
        headers.set("ETag", etag);
        headers.set("Access-Control-Allow-Origin", "*");
        headers.set("Vary", "Accept");
        const finalRes = new Response(assetRes.body, {
          status: 200,
          headers,
        });
        if (cache && ctx?.waitUntil) {
          ctx.waitUntil(cache.put(cacheKey, finalRes.clone()));
        }
        return finalRes;
      }
    } catch {
      // fall through to GitHub Raw proxy
    }
  }

  // 4. Fallback: Fetch from GitHub Raw
  try {
    if (supportsWebp) {
      const ghWebpUrl = `https://raw.githubusercontent.com/egorgrebennykov-del/Al-Warda/main/Al-Warda/public/assets/img/generated-products/${hash}.webp`;
      const ghWebpRes = await fetch(ghWebpUrl);
      if (ghWebpRes && ghWebpRes.ok) {
        const headers = new Headers(ghWebpRes.headers);
        headers.set("Content-Type", "image/webp");
        headers.set(
          "Cache-Control",
          "public, max-age=31536000, s-maxage=31536000, immutable",
        );
        headers.set("ETag", etag);
        headers.set("Access-Control-Allow-Origin", "*");
        headers.set("Vary", "Accept");
        const finalRes = new Response(ghWebpRes.body, { status: 200, headers });
        if (cache && ctx?.waitUntil) {
          ctx.waitUntil(cache.put(cacheKey, finalRes.clone()));
        }
        return finalRes;
      }
    }

    const rawGithubUrl = `https://raw.githubusercontent.com/egorgrebennykov-del/Al-Warda/main/Al-Warda/public/assets/img/generated-products/${hash}.${requestedExt}`;
    const ghResponse = await fetch(rawGithubUrl);
    if (ghResponse && ghResponse.ok) {
      const headers = new Headers(ghResponse.headers);
      headers.set(
        "Content-Type",
        requestedExt === "webp" ? "image/webp" : "image/png",
      );
      headers.set(
        "Cache-Control",
        "public, max-age=31536000, s-maxage=31536000, immutable",
      );
      headers.set("ETag", etag);
      headers.set("Access-Control-Allow-Origin", "*");
      headers.set("Vary", "Accept");
      const finalRes = new Response(ghResponse.body, { status: 200, headers });
      if (cache && ctx?.waitUntil) {
        ctx.waitUntil(cache.put(cacheKey, finalRes.clone()));
      }
      return finalRes;
    }
  } catch {
    // fall through
  }

  return new Response("Not found", { status: 404 });
}

export default {
  async fetch(request, env, ctx) {
    try {
      syncProcessEnv(env);

      if (request.method.toUpperCase() === "OPTIONS") {
        return new Response(null, {
          status: 204,
          headers: {
            "Access-Control-Allow-Origin": "*",
            "Access-Control-Allow-Methods": "GET, POST, OPTIONS, PATCH, DELETE",
            "Access-Control-Allow-Headers":
              "Content-Type, Authorization, apikey",
          },
        });
      }

      const urlObj = new URL(request.url);
      const { pathname } = urlObj;
      const method = request.method.toUpperCase();

      // PostgREST-style data layer (Supabase /rest/v1/*) translated to Nhost
      // Hasura GraphQL. Admin secret stays server-side; never sent to browser.
      // Also accept /api/rest/v1/* — the /api/* asset route reliably reaches
      // the Worker (see wrangler.jsonc run_worker_first).
      if (
        pathname.startsWith("/rest/v1/") ||
        pathname.startsWith("/api/rest/v1/")
      ) {
        return handleRestProxy(request, env);
      }

      if (method === "GET" && pathname === "/health") {
        return jsonResponse({ ok: true, store: "Al-Warda Parfumes" });
      }

      if (method === "GET" && pathname === "/api/fragrance-notes") {
        return getFragranceNotes(request, env);
      }
      if (
        method === "GET" &&
        pathname === "/api/admin/fragrance-notes/misses"
      ) {
        return getFragranceNotesQueue(request, env);
      }
      if (
        method === "POST" &&
        pathname === "/api/admin/fragrance-notes/refresh"
      ) {
        return refreshFragranceNotes(request, env);
      }

      if (method === "GET" && pathname === "/api/admin/descriptions/misses") {
        return getDescriptionQueue(request, env);
      }
      if (method === "POST" && pathname === "/api/admin/descriptions/refresh") {
        return refreshDescriptions(request, env);
      }
      if (method === "POST" && pathname === "/api/admin/descriptions/clear") {
        return clearDescriptions(request, env);
      }

      if (method === "GET" && pathname === "/api/admin/product-images/status") {
        return getProductImageQueueStatus(request, env);
      }
      if (pathname.startsWith("/api/admin/gpu-generation/")) {
        return jsonResponse({
          ok: true,
          isCloudflare: true,
          isRunning: false,
          environment: {
            hasLocalPython: false,
            hasUpscaylGpu: false,
            message: "Cloudflare edge worker runtime. GPU generation connects to local machine runner.",
          },
        });
      }
      if (
        (method === "POST" || method === "DELETE") &&
        pathname === "/api/admin/product-images/failed"
      ) {
        return deleteFailedProductItems(request, env);
      }
      if (
        method === "POST" &&
        pathname === "/api/admin/product-images/requeue"
      ) {
        return requeueFailedProductItems(request, env);
      }
      if (
        method === "POST" &&
        pathname === "/api/admin/product-images/mark-failed"
      ) {
        return markProductItemsFailed(request, env);
      }
      if (
        method === "POST" &&
        pathname === "/api/admin/product-images/unmark-failed"
      ) {
        return unmarkProductItemsFailed(request, env);
      }
      if (
        method === "POST" &&
        pathname === "/api/admin/product-images/manual-save"
      ) {
        return saveManualProductItem(request, env);
      }
      if (method === "GET" && pathname === "/api/admin/products") {
        return getAllAdminProducts(request, env);
      }
      if (
        (method === "DELETE" || method === "POST") &&
        (pathname === "/api/admin/products/delete" ||
          pathname === "/api/admin/products")
      ) {
        return deleteAdminProducts(request, env);
      }
      if (pathname === "/api/admin/settings" && method === "GET")
        return getSiteSettings(request, env);
      if (pathname === "/api/admin/settings" && method === "POST")
        return saveSiteSettings(request, env);
      if (pathname === "/api/admin/product-images/actions") {
        return handleProductImageActions(request, env);
      }

      if (
        pathname.startsWith("/api/qogita/") &&
        pathname !== "/api/qogita/arabian-perfumes"
      ) {
        return handleQogitaWorker(request, env);
      }

      if (
        pathname.startsWith("/api/admin/pricing") ||
        pathname.startsWith("/api/pricing/")
      ) {
        const pricingResponse = await handlePricingRequest(request, env, urlObj);
        if (pricingResponse) return pricingResponse;
      }

      if (method === "POST" && pathname === "/api/warmup") {
        return jsonResponse({ ready: true });
      }

      if (method === "GET" && pathname === "/api/product-image") {
        const gtin =
          urlObj.searchParams.get("gtin") || urlObj.searchParams.get("id");
        if (!gtin) return new Response("Missing gtin", { status: 400 });
        return env.ASSETS.fetch(
          new Request(new URL(`/assets/img/products/${gtin}.jpg`, request.url)),
        );
      }

      if (method === "GET" && pathname === "/api/transparent-image") {
        const targetUrl = urlObj.searchParams.get("url");
        if (!targetUrl) return new Response("Missing url", { status: 400 });
        const cache =
          typeof caches !== "undefined" && caches.default
            ? caches.default
            : null;
        const cacheKey = new Request(request.url, { method: "GET" });
        if (cache) {
          try {
            const cached = await cache.match(cacheKey);
            if (cached) return cached;
          } catch {
            // ignore cache match error
          }
        }
        try {
          const upstream = await fetch(targetUrl, {
            headers: {
              "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)",
            },
          });
          const headers = new Headers(upstream.headers);
          headers.set("Access-Control-Allow-Origin", "*");
          headers.set(
            "Cache-Control",
            "public, max-age=31536000, s-maxage=31536000, immutable",
          );
          const finalRes = new Response(upstream.body, {
            status: upstream.status,
            headers,
          });
          if (cache && ctx?.waitUntil && upstream.ok) {
            ctx.waitUntil(cache.put(cacheKey, finalRes.clone()));
          }
          return finalRes;
        } catch (e) {
          return new Response(e.message, { status: 502 });
        }
      }

      // Stocks API (Supabase proxy / fallback)
      if (
        method === "GET" &&
        (pathname === "/api/stocks" ||
          pathname === "/api/qogita/arabian-perfumes" ||
          pathname === "/api/dropship-perfumes")
      ) {
        const q = urlObj.searchParams.get("q")?.toLowerCase();
        let list = cachedArabianPerfumes.filter(isReadyProduct);
        if (q) {
          list = list.filter(
            (p) =>
              p.name?.toLowerCase().includes(q) ||
              p.brand?.toLowerCase().includes(q),
          );
        }
        const limitRaw = urlObj.searchParams.get("limit");
        const offsetRaw = urlObj.searchParams.get("offset");
        const allRaw = urlObj.searchParams.get("all") === "1";
        const limit =
          limitRaw && /^\d+$/.test(limitRaw)
            ? Math.min(parseInt(limitRaw, 10), 300)
            : 96;
        const offset =
          offsetRaw && /^\d+$/.test(offsetRaw)
            ? Math.max(parseInt(offsetRaw, 10), 0)
            : 0;
        const sliced = allRaw ? list : list.slice(offset, offset + limit);
        // Never leak invented note pyramids from the cached catalog: enrichPerfumeObj
        // keeps only notes generated by DeepSeek or entered manually.
        return jsonResponse({
          count: list.length,
          results: sliced.map((p) =>
            completedProductPhoto(enrichPerfumeObj(p)),
          ),
          limit: allRaw ? list.length : limit,
          offset: allRaw ? 0 : offset,
          all: allRaw,
        });
      }

      // Perfume list API
      if (method === "GET" && pathname === "/api/perfumes") {
        const q = urlObj.searchParams.get("q")?.toLowerCase();
        let list = cachedArabianPerfumes.filter(isReadyProduct);
        if (q) {
          list = list.filter(
            (p) =>
              p.name?.toLowerCase().includes(q) ||
              p.brand?.toLowerCase().includes(q),
          );
        }
        return jsonResponse({
          perfumes: list.map((p) => completedProductPhoto(enrichPerfumeObj(p))),
        });
      }

      // Single perfume details API (supports direct ID, slug, or SEO URL with name)
      if (method === "GET" && pathname.startsWith("/api/perfumes/")) {
        const rawParam = decodeURIComponent(
          pathname.replace("/api/perfumes/", ""),
        )
          .toLowerCase()
          .trim();
        let p = cachedArabianPerfumes
          .filter(isReadyProduct)
          .find(
            (x) =>
              x.id?.toLowerCase() === rawParam ||
              x.slug?.toLowerCase() === rawParam,
          );
        if (!p) {
          const trailingDropship = rawParam.match(/(dropship-\d+)$/i);
          if (trailingDropship) {
            p = cachedArabianPerfumes
              .filter(isReadyProduct)
              .find((x) => x.id?.toLowerCase() === trailingDropship[1]);
          }
        }
        if (!p) {
          const trailingNum = rawParam.match(/-(\d+)$/);
          if (trailingNum) {
            p = cachedArabianPerfumes
              .filter(isReadyProduct)
              .find((x) => x.id === trailingNum[1]);
          }
        }
        if (!p) {
          const letters = rawParam.replace(/[^a-z0-9]/g, "");
          p = cachedArabianPerfumes.filter(isReadyProduct).find((x) => {
            const xLetters = (x.name || "")
              .toLowerCase()
              .replace(/[^a-z0-9]/g, "");
            return (
              xLetters &&
              (letters === xLetters ||
                letters.includes(xLetters) ||
                xLetters.includes(letters))
            );
          });
        }
        if (p) return jsonResponse(completedProductPhoto(enrichPerfumeObj(p)));
        return jsonResponse({ error: "Not found" }, 404);
      }

      // AI Concierge Chat (Yasmin)
      if (
        method === "POST" &&
        (pathname === "/api/warda-chat" || pathname === "/api/warda-chat")
      ) {
        try {
          const body = await request.json().catch(() => ({}));
          const isSse = request.headers
            .get("accept")
            ?.includes("text/event-stream");

          if (isSse) {
            const encoder = new TextEncoder();
            const { readable, writable } = new TransformStream();
            const writer = writable.getWriter();

            const streamPromise = (async () => {
              try {
                const onStatus = async (status) => {
                  await writer.write(
                    encoder.encode(
                      `data: ${JSON.stringify({ type: "status", status })}\n\n`,
                    ),
                  );
                };
                const result = await processWardaChat({ ...body, onStatus });
                await writer.write(
                  encoder.encode(
                    `data: ${JSON.stringify({ type: "result", ...result })}\n\n`,
                  ),
                );
                await writer.write(encoder.encode("data: [DONE]\n\n"));
              } catch (err) {
                await writer.write(
                  encoder.encode(
                    `data: ${JSON.stringify({ type: "error", error: err.message })}\n\n`,
                  ),
                );
              } finally {
                await writer.close();
              }
            })();

            if (ctx?.waitUntil) ctx.waitUntil(streamPromise);

            return new Response(readable, {
              headers: {
                "Content-Type": "text/event-stream; charset=utf-8",
                "Cache-Control": "no-cache",
                Connection: "keep-alive",
                "Access-Control-Allow-Origin": "*",
              },
            });
          }

          const result = await processWardaChat(body);
          return jsonResponse(result);
        } catch (err) {
          return jsonResponse(
            {
              error: "Yasmin assistant failed to respond",
              message: err.message,
            },
            500,
          );
        }
      }

      if (
        method === "POST" &&
        (pathname === "/api/warda-translate" ||
          pathname === "/api/warda-translate")
      ) {
        try {
          const body = await request.json().catch(() => ({}));
          const result = await translateWardaDialog({
            messages: body?.messages,
            targetLanguage: body?.targetLanguage,
          });
          return jsonResponse(result);
        } catch (err) {
          return jsonResponse({ translations: [], error: err.message }, 500);
        }
      }

      if (method === "POST" && pathname === "/api/translate-announcement") {
        try {
          const body = await request.json().catch(() => ({}));
          const result = await translateAnnouncementText({ text: body?.text });
          return jsonResponse(result);
        } catch (err) {
          return jsonResponse({ error: err.message }, 500);
        }
      }

      if (method === "POST" && pathname === "/api/enrich-perfume") {
        try {
          const body = await request.json().catch(() => ({}));
          const result = await enrichPerfumeWithAI(body || {});
          return jsonResponse(result);
        } catch (err) {
          return jsonResponse({ error: err.message }, 500);
        }
      }

      if (method === "POST" && pathname === "/api/filter-inquiry-message") {
        try {
          const body = await request.json().catch(() => ({}));
          const { text, language } = body || {};
          const result = await filterInquiryMessageWithAI({ text, language });
          return jsonResponse(result);
        } catch (err) {
          return jsonResponse({ allowed: false, message: err.message }, 500);
        }
      }

      if (method === "POST" && pathname === "/api/send-inquiry-email") {
        try {
          const body = await request.json().catch(() => ({}));
          const { to, userName, subject, text, adminName } = body || {};
          if (!to || !text) {
            return jsonResponse(
              { error: "Missing required fields: to, text" },
              400,
            );
          }
          const result = await sendGuestInquiryEmail({
            to,
            userName,
            subject,
            text,
            adminName,
          });
          return jsonResponse({ success: true, result });
        } catch (err) {
          return jsonResponse(
            { error: "Failed to send inquiry email", message: err.message },
            500,
          );
        }
      }

      if (method === "GET" && pathname === "/api/actions-status") {
        return jsonResponse({ actions: actionStatuses });
      }

      if (pathname.startsWith("/api/")) {
        return jsonResponse({ error: "Endpoint not found" }, 404);
      }

      if (
        /^\/assets\/img\/generated-products\/[a-f0-9]{64}\.(png|webp)$/.test(
          pathname,
        )
      ) {
        const generatedRes = await serveGeneratedProductImage(
          request,
          pathname,
          env,
          ctx,
        );
        if (generatedRes) return generatedRes;
      }

      // Static assets & SPA fallback
      if (env?.ASSETS) {
        const response = await env.ASSETS.fetch(request);
        if (response && response.ok) {
          const headers = new Headers(response.headers);
          if (pathname.startsWith("/assets/")) {
            headers.set("Cache-Control", "public, max-age=31536000, immutable");
          } else {
            headers.set(
              "Cache-Control",
              "public, max-age=604800, stale-while-revalidate=86400",
            );
          }
          return new Response(response.body, {
            status: response.status,
            statusText: response.statusText,
            headers,
          });
        }
        return response;
      }

      return new Response("Not found", { status: 404 });
    } catch (err) {
      console.error("Worker unhandled fetch error:", err);
      return jsonResponse(
        {
          error: err?.message || "Internal server error",
          code: "INTERNAL_SERVER_ERROR",
        },
        500,
      );
    }
  },
};
